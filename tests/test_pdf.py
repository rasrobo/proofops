"""Tests for PDF checks.

The PDFs here are generated by a small writer in this file (valid object table and xref), not
downloaded, so the tests are deterministic and the expected page count comes from construction
rather than from another parser agreeing with ours.

The important test is `test_a_scanned_page_is_not_reported_as_missing_text`: "we could not read
this document" must not be recorded as "the text is not there". Conflating those is the
overclaim this tool exists to prevent.
"""

import pathlib
import sys
import tempfile
import unittest
import zlib

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from proofops import artifacts as art   # noqa: E402
from proofops import pdfdoc             # noqa: E402


def make_pdf(pages: list[str], size: tuple[int, int] = (595, 842),
             compress: bool = False) -> bytes:
    """A minimal but well-formed PDF: catalog, page tree, font, one content stream per page."""
    w, h = size
    objs: dict[int, bytes] = {}
    n = len(pages)
    kids = " ".join(f"{4 + 2 * i} 0 R" for i in range(n))
    objs[1] = b"<< /Type /Catalog /Pages 2 0 R >>"
    objs[2] = f"<< /Type /Pages /Kids [{kids}] /Count {n} >>".encode()
    objs[3] = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"
    for i, text in enumerate(pages):
        body = f"BT /F1 24 Tf 72 720 Td ({text}) Tj ET".encode()
        filter_ = b""
        if compress:
            body = zlib.compress(body)
            filter_ = b" /Filter /FlateDecode"
        objs[4 + 2 * i] = (f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {w} {h}] "
                           f"/Resources << /Font << /F1 3 0 R >> >> "
                           f"/Contents {5 + 2 * i} 0 R >>").encode()
        objs[5 + 2 * i] = (f"<< /Length {len(body)}{filter_.decode()} >>".encode()
                           + b"\nstream\n" + body + b"\nendstream")

    out = bytearray(b"%PDF-1.7\n")
    offsets = {}
    for num in sorted(objs):
        offsets[num] = len(out)
        out += f"{num} 0 obj\n".encode() + objs[num] + b"\nendobj\n"
    xref_at = len(out)
    size_total = max(objs) + 1
    out += f"xref\n0 {size_total}\n".encode()
    out += b"0000000000 65535 f \n"
    for num in range(1, size_total):
        out += f"{offsets.get(num, 0):010d} 00000 n \n".encode()
    out += (f"trailer\n<< /Size {size_total} /Root 1 0 R >>\nstartxref\n{xref_at}\n"
            f"%%EOF\n").encode()
    return bytes(out)


class Corpus:
    def __enter__(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self.tmp.name)
        (self.root / "report.pdf").write_bytes(
            make_pdf(["Invoice 2026-11", "Terms and conditions"]))
        (self.root / "zipped.pdf").write_bytes(
            make_pdf(["Compressed body text"], compress=True))
        (self.root / "scanned.pdf").write_bytes(make_pdf(["placeholder"], compress=False)
                                                .replace(b"(placeholder) Tj", b"0 0 100 100 re f"))
        (self.root / "notpdf.txt").write_text("hello")
        art.set_policy(art.PathPolicy((str(self.root),)))
        return self

    def __exit__(self, *exc):
        self.tmp.cleanup()


class TestPdfPages(unittest.TestCase):
    def test_page_count_from_the_page_tree(self):
        with Corpus() as c:
            ok, ev = pdfdoc.pdf_pages({"path": "report.pdf", "equals": 2}, "local")
            self.assertTrue(ok, ev)
            self.assertEqual(ev["observed_pages"], 2)
            self.assertIn("page tree", ev["method"])

    def test_wrong_page_count_fails_and_says_what_it_saw(self):
        with Corpus() as c:
            ok, ev = pdfdoc.pdf_pages({"path": "report.pdf", "equals": 3}, "local")
            self.assertFalse(ok)
            self.assertEqual(ev["observed_pages"], 2)

    def test_a_non_pdf_is_reported_not_crashed(self):
        with Corpus() as c:
            ok, ev = pdfdoc.pdf_pages({"path": "notpdf.txt", "equals": 1}, "local")
            self.assertFalse(ok)
            self.assertIn("not a PDF", ev["error"])

    def test_path_escape_is_refused_by_the_shared_policy(self):
        with Corpus() as c:
            ok, ev = pdfdoc.pdf_pages({"path": "../../etc/passwd", "equals": 1}, "local")
            self.assertFalse(ok)
            self.assertIn("allowed_paths", ev["error"])


class TestPdfPageSize(unittest.TestCase):
    def test_page_size_from_mediabox(self):
        with Corpus() as c:
            ok, ev = pdfdoc.pdf_page_size({"path": "report.pdf", "width": 595, "height": 842},
                                          "local")
            self.assertTrue(ok, ev)
            self.assertEqual(ev["observed"], "595.0x842.0pt")

    def test_wrong_size_fails(self):
        with Corpus() as c:
            ok, _ = pdfdoc.pdf_page_size({"path": "report.pdf", "width": 612, "height": 792},
                                         "local")
            self.assertFalse(ok)


class TestPdfText(unittest.TestCase):
    def test_text_is_found_in_plain_streams(self):
        with Corpus() as c:
            ok, ev = pdfdoc.pdf_text_contains({"path": "report.pdf", "contains": "Invoice"},
                                              "local")
            self.assertTrue(ok, ev)
            self.assertIn("Invoice", ev["snippet"])

    def test_text_is_found_in_compressed_streams(self):
        with Corpus() as c:
            ok, ev = pdfdoc.pdf_text_contains({"path": "zipped.pdf",
                                               "contains": "Compressed body"}, "local")
            self.assertTrue(ok, ev)
            self.assertGreaterEqual(ev["decoded_streams"], 1)

    def test_absent_text_fails(self):
        with Corpus() as c:
            ok, ev = pdfdoc.pdf_text_contains({"path": "report.pdf", "contains": "Receipt"},
                                              "local")
            self.assertFalse(ok)
            self.assertNotIn("error", ev)

    def test_a_scanned_page_is_not_reported_as_missing_text(self):
        """A PDF we cannot read is a different answer from a PDF that lacks the text."""
        with Corpus() as c:
            ok, ev = pdfdoc.pdf_text_contains({"path": "scanned.pdf", "contains": "Invoice"},
                                              "local")
            self.assertFalse(ok)
            self.assertIn("no extractable text", ev["error"])
            self.assertIn("cannot answer", ev["error"])


if __name__ == "__main__":
    unittest.main(verbosity=2)
